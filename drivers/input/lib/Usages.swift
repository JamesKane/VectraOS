// The input class (D83): keyboard drivers push HID usages of the keyboard
// page (0x07) to kbdfs's kbin, as 2-byte records: the usage, then 1 for a
// press or 0 for a release. A USB keyboard's usages pass through; this is
// the one table for devices that report evdev's codes (virtio-input, as
// Linux does), from evdev's key codes to the usages HID gives the same
// keys (USB HID Usage Tables 1.5, §10).

public enum KeyboardUsage {
  /// The kbin record for `usage` pressed or released.
  public static func record(_ usage: UInt8, down: Bool) -> [UInt8] { [usage, down ? 1 : 0] }

  /// The usage evdev's key `code` is (0: none).
  public static func of(evdev code: UInt16) -> UInt8 { code < UInt16(evdev.count) ? evdev[Int(code)] : 0 }

  /// evdev's codes 0-127 (KEY_ESC 1 ... KEY_COMPOSE 127) to usages.
  static let evdev: [UInt8] = [
    0x00, 0x29, 0x1E, 0x1F, 0x20, 0x21, 0x22, 0x23,  // -, Esc, 1-6
    0x24, 0x25, 0x26, 0x27, 0x2D, 0x2E, 0x2A, 0x2B,  // 7-0, - =, Backspace, Tab
    0x14, 0x1A, 0x08, 0x15, 0x17, 0x1C, 0x18, 0x0C,  // q w e r t y u i
    0x12, 0x13, 0x2F, 0x30, 0x28, 0xE0, 0x04, 0x16,  // o p [ ], Enter, LeftCtrl, a s
    0x07, 0x09, 0x0A, 0x0B, 0x0D, 0x0E, 0x0F, 0x33,  // d f g h j k l ;
    0x34, 0x35, 0xE1, 0x31, 0x1D, 0x1B, 0x06, 0x19,  // ' `, LeftShift, \ z x c v
    0x05, 0x11, 0x10, 0x36, 0x37, 0x38, 0xE5, 0x55,  // b n m , . /, RightShift, KP*
    0xE2, 0x2C, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E,  // LeftAlt, Space, CapsLock, F1-F5
    0x3F, 0x40, 0x41, 0x42, 0x43, 0x53, 0x47, 0x5F,  // F6-F10, NumLock, ScrollLock, KP7
    0x60, 0x61, 0x56, 0x5C, 0x5D, 0x5E, 0x57, 0x59,  // KP8 KP9 KP- KP4 KP5 KP6 KP+ KP1
    0x5A, 0x5B, 0x62, 0x63, 0x00, 0x94, 0x64, 0x44,  // KP2 KP3 KP0 KP., -, Zenkaku, 102nd, F11
    0x45, 0x87, 0x92, 0x93, 0x8A, 0x88, 0x8B, 0x8C,  // F12, Ro, Katakana, Hiragana, Henkan, KataHira, Muhenkan, KP,
    0x58, 0xE4, 0x54, 0x46, 0xE6, 0x00, 0x4A, 0x52,  // KPEnter, RightCtrl, KP/, SysRq, RightAlt, -, Home, Up
    0x4B, 0x50, 0x4F, 0x4D, 0x51, 0x4E, 0x49, 0x4C,  // PageUp, Left, Right, End, Down, PageDown, Insert, Delete
    0x00, 0x7F, 0x81, 0x80, 0x66, 0x67, 0x00, 0x48,  // -, Mute, VolumeDown, VolumeUp, Power, KP=, -, Pause
    0x00, 0x85, 0x90, 0x91, 0x89, 0xE3, 0xE7, 0x65,  // -, KP comma, Hangeul, Hanja, Yen, LeftMeta, RightMeta, Compose
  ]
}
