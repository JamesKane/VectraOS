// The note that ties a program to the build of each library it was linked
// against (D124): one ELF note per library, owner "croi", type
// `libraryNoteType`, whose descriptor is the library's GNU build ID's
// length (a 32-bit word), the build ID, then its soname. vx library-note
// writes it as C, an array in a `.note.croi.libraries` section, which the
// program or library is linked with; the process that starts it reads the
// note from its PT_NOTE and refuses a library whose build ID differs
// (user/lib/loader's Linked.swift).

/// The note's type.
public let libraryNoteType: UInt32 = 0x100

/// A shared object's DT_SONAME and GNU build ID (NT_GNU_BUILD_ID), from
/// its program headers.
public func sonameAndBuildID(_ elf: [UInt8]) throws(FormatError) -> (soname: [UInt8], buildID: [UInt8]) {
  try elf.checked(0, 64)
  guard elf[0] == 0x7F, elf[1] == 0x45, elf[2] == 0x4C, elf[3] == 0x46, elf[4] == 2, elf[5] == 1 else {
    throw FormatError("not a little-endian ELF64")
  }
  let phoff = Int(elf.u64(0x20)), phentsize = Int(elf.u16(0x36)), phnum = Int(elf.u16(0x38))
  var loads: [(offset: UInt64, vaddr: UInt64, filesz: UInt64)] = []
  var dynamic: (offset: Int, size: Int)?
  var buildID: [UInt8]?
  for i in 0..<phnum {
    let at = phoff + i * phentsize
    try elf.checked(at, 56)
    let offset = Int(elf.u64(at + 8)), size = Int(elf.u64(at + 32))
    switch elf.u32(at) {
    case 1: loads.append((elf.u64(at + 8), elf.u64(at + 16), elf.u64(at + 32)))
    case 2: dynamic = (offset, size)
    case 4:  // PT_NOTE
      try elf.checked(offset, size)
      var n = offset
      while n + 12 <= offset + size {
        let namesz = Int(elf.u32(n)), descsz = Int(elf.u32(n + 4)), type = elf.u32(n + 8)
        let name = n + 12, desc = name + (namesz + 3) & ~3
        try elf.checked(desc, descsz)
        if type == 3, namesz == 4, Array(elf[name..<name + 4]) == Array("GNU\0".utf8) {
          buildID = Array(elf[desc..<desc + descsz])
        }
        n = desc + (descsz + 3) & ~3
      }
    default: break
    }
  }
  guard let buildID else { throw FormatError("no GNU build ID (link with --build-id)") }
  guard let dynamic else { throw FormatError("no dynamic section") }
  try elf.checked(dynamic.offset, dynamic.size)
  var strtab: UInt64?
  var soname: UInt64?
  for at in stride(from: dynamic.offset, to: dynamic.offset + dynamic.size - 15, by: 16) {
    switch elf.u64(at) {
    case 5: strtab = elf.u64(at + 8)
    case 14: soname = elf.u64(at + 8)
    default: break
    }
  }
  guard let strtab, let soname else { throw FormatError("no DT_SONAME") }
  guard let load = loads.first(where: { strtab >= $0.vaddr && strtab - $0.vaddr < $0.filesz }) else {
    throw FormatError("DT_STRTAB outside the file")
  }
  var at = Int(load.offset + (strtab - load.vaddr) + soname)
  var name: [UInt8] = []
  while true {
    try elf.checked(at, 1)
    if elf[at] == 0 { break }
    name.append(elf[at])
    at += 1
  }
  return (name, buildID)
}

/// The notes' bytes, one per library: its soname and build ID.
public func libraryNotes(_ libraries: [(soname: [UInt8], buildID: [UInt8])]) -> [UInt8] {
  var out: [UInt8] = []
  func word(_ v: Int) { for s in 0..<4 { out.append(UInt8(truncatingIfNeeded: v >> (8 * s))) } }
  func pad() { while out.count % 4 != 0 { out.append(0) } }
  for l in libraries {
    word(5)
    word(4 + l.buildID.count + l.soname.count)
    word(Int(libraryNoteType))
    out += Array("croi\0".utf8)
    pad()
    word(l.buildID.count)
    out += l.buildID + l.soname
    pad()
  }
  return out
}

/// The notes as C: a byte array in a note section, kept by the compiler
/// and (a note) by the linker.
public func libraryNoteSource(_ libraries: [(soname: [UInt8], buildID: [UInt8])]) -> String {
  let bytes = libraryNotes(libraries)
  var lines = ["// Generated by vx library-note: the libraries this object was linked against, and their build IDs.",
               "__attribute__((section(\".note.croi.libraries\"), used, aligned(4)))",
               "static const unsigned char croi_library_notes[\(max(bytes.count, 1))] = {"]
  for start in stride(from: 0, to: bytes.count, by: 16) {
    lines.append("  " + bytes[start..<min(start + 16, bytes.count)].map { "\($0)," }.joined(separator: " "))
  }
  lines.append("};")
  return lines.joined(separator: "\n") + "\n"
}
