// Usage messages from pages (D86): each command's message is its page's
// `usage` fence, so the two can't differ. The commands library's are
// generated into a Swift file (`vx man --usage`), committed, and checked
// against the pages by `vx man --check`.

import Guide

/// A Swift file of usage messages, and where its commands are named.
public struct UsageFile: Sendable {
  public var path: String
  /// The file whose `static let names` lists the commands.
  public var commands: String
}

public let usageFiles = [
  UsageFile(path: "shell/commands/lib/Usage.swift", commands: "shell/commands/lib/Commands.swift")
]

public enum UsageMessages {
  /// A command's message: the lines of its page's usage fences that
  /// start with its name, `usage: ` before the first and the others under it.
  public static func lines(_ page: Page, command: String) -> [String]? {
    var synopsis = false
    var found: [Substring] = []
    for b in page.blocks {
      if b.kind == .heading { synopsis = b.text == Array("SYNOPSIS".utf8) }
      guard synopsis, b.kind == .fence, b.fence == .usage else { continue }
      for l in String(decoding: b.text, as: UTF8.self).split(separator: "\n")
      where l.split(separator: " ").first.map(String.init) == command {
        found.append(l)
      }
    }
    guard !found.isEmpty else { return nil }
    return found.enumerated().map { ($0.offset == 0 ? "usage: " : "       ") + $0.element }
  }

  /// The Swift file for `commands`, or the names that have no page with a
  /// usage fence in section 1.
  public static func swift(_ manual: Manual, commands: [String]) -> Result<String, Missing> {
    var out = """
      // SPDX-License-Identifier: BSD-3-Clause

      // Generated by `vx man --usage` from each command's page, the usage
      // fence in its SYNOPSIS (D86); `vx man --check` keeps it in step.
      // Don't edit it: edit the page.

      enum Usage {

      """
    var missing: [String] = []
    for c in commands {
      guard let p = manual.lookup(c, section: 1), let lines = lines(p.page, command: c) else {
        missing.append(c)
        continue
      }
      let literal = lines.map { "\"" + $0.replacingAll("\\", "\\\\").replacingAll("\"", "\\\"") + "\"" }
      out += "  static let \(c.replacingAll("-", "_")) = [\(literal.joined(separator: ", "))]\n"
    }
    out += "}\n"
    return missing.isEmpty ? .success(out) : .failure(Missing(names: missing))
  }

  public struct Missing: Error {
    public var names: [String]
  }
}

extension String {
  func replacingAll(_ a: String, _ b: String) -> String { split(separator: a, omittingEmptySubsequences: false).joined(separator: b) }
}
