// vx shaders (D121, after todhchai's td shaders): compiles GLSL to SPIR-V
// with the host's glslangValidator (a compiler producing our artifact
// format, D4). Every .vert, .frag and .comp in the tree (but build output
// and data) gets a .spv beside it, which is committed, so a build needs no
// shader compiler. --check recompiles and fails if any committed .spv is
// missing or stale. Programs' shaders also go into a Swift file of byte
// arrays (`shaderArrays`), since native programs have no files to read them
// from.

import HostSystem

func shaderSources() -> [String] {
  var command = ["find", "."]
  for dir in ["./.build", "./build", "./.cache", "./bench", "./.git", "./data", "./.claude"] {
    command += ["-path", dir, "-prune", "-o"]
  }
  command += ["(", "-name", "*.vert", "-o", "-name", "*.frag", "-o", "-name", "*.comp", ")", "-print"]
  return (capture(command) ?? "").split(separator: "\n").map { String($0.dropFirst(2)) }.sorted()
}

/// Directories whose SPIR-V also goes into a Swift file, as an enum's arrays.
let shaderArrays = [
  ("graphics/loinnir/tests/shaders", "graphics/loinnir/tests/native/generated/LoinnirShaders.swift", "LoinnirShaders"),
  ("services/radharc/shaders", "services/radharc/gpu/generated/Shaders.swift", "RadharcShaders"),
]

func shadersCommand(_ args: [String]) -> Bool {
  let check = args.contains("--check")
  var ok = true
  let scratch = "/tmp/vx-shaders-\(getpid())"
  makeDirectory(scratch)
  defer { removeTree(scratch) }
  for source in shaderSources() {
    let target = source + ".spv"
    let output = check ? "\(scratch)/out.spv" : target
    let log = "\(scratch)/log"
    guard run(["glslangValidator", "-V", "--target-env", "vulkan1.3", "-o", output, source], log: log).ok else {
      complain("\(source) doesn't compile:\n" + ((try? String(contentsOfFile: log, encoding: .utf8)) ?? ""))
      ok = false
      continue
    }
    if check {
      if FileManager.default.contents(atPath: output) != FileManager.default.contents(atPath: target) {
        complain("\(target) is \(FileManager.default.fileExists(atPath: target) ? "stale" : "missing"): run vx shaders")
        ok = false
      }
    } else {
      say("  \(target)")
    }
  }
  for (dir, generated, name) in shaderArrays {
    let swift = shadersSwift(dir, name)
    if check {
      if (try? String(contentsOfFile: generated, encoding: .utf8)) != swift {
        complain("\(generated) is stale: run vx shaders")
        ok = false
      }
    } else {
      makeDirectory(String(generated[..<generated.lastIndex(of: "/")!]))
      _ = try? swift.write(toFile: generated, atomically: true, encoding: .utf8)
      say("  \(generated)")
    }
  }
  return ok
}

/// `dir`'s SPIR-V as Swift arrays: `triangleVert` for triangle.vert.spv,
/// and so on.
func shadersSwift(_ dir: String, _ enumName: String) -> String {
  let names = ((try? FileManager.default.contentsOfDirectory(atPath: dir)) ?? []).filter { $0.hasSuffix(".spv") }.sorted()
  var out = """
    // SPDX-License-Identifier: BSD-3-Clause
    //
    // Generated by vx shaders from \(dir). Do not edit; regenerate (vx shaders).
    // Its shaders as arrays, for native programs, which have no files to read.

    enum \(enumName) {

    """
  for name in names {
    let parts = name.dropLast(4).split(separator: ".")  // triangle.vert
    let id = parts[0] + parts.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
    let bytes = [UInt8](FileManager.default.contents(atPath: "\(dir)/\(name)") ?? Data())
    out += "  static let \(id): [UInt8] = [\n"
    var i = 0
    while i < bytes.count {
      let row = bytes[i..<min(i + 16, bytes.count)].map { b -> String in
        let h = String(b, radix: 16)
        return "0x" + (h.count < 2 ? "0" + h : h)
      }
      out += "    " + row.joined(separator: ", ") + ",\n"
      i += 16
    }
    out += "  ]\n"
  }
  return out + "}\n"
}
