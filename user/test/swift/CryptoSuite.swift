import CroiRuntime

/// Crypto (D89) built as Embedded Swift and run on the target: one
/// published vector each, BLAKE3's, FIPS 180's, RFC 4231's, RFC 8439's,
/// RFC 7748's, RFC 8032's and RFC 7914's. CryptoTests runs all of their
/// suites and libsec's oracle on the host; this checks the code as built
/// here, with no compiler-rt (a 128-bit multiply would fail the link).
enum CryptoSuite {
    static func run() {
        hashes()
        ciphers()
        curves()
        print("swift: crypto passed")
    }

    static func hashes() {
        // The empty input, and 1,025 bytes of the vectors' 0...250 pattern (two chunks).
        let empty: [UInt8] = [0xaf, 0x13, 0x49, 0xb9, 0xf5, 0xf9, 0xa1, 0xa6, 0xa0, 0x40, 0x4d, 0xea, 0x36, 0xdc, 0xc9, 0x49]
        check(BLAKE3.hash([], count: 16) == empty, "blake3, empty")
        let input = (0..<1025).map { UInt8($0 % 251) }
        let expected: [UInt8] = [0xd0, 0x02, 0x78, 0xae, 0x47, 0xeb, 0x27, 0xb3, 0x4f, 0xae, 0xcf, 0x67, 0xb4, 0xfe, 0x26, 0x3f]
        check(BLAKE3.hash(input, count: 16) == expected, "blake3, two chunks")
        check(SHA256.hash(Array("abc".utf8)) == [0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40, 0xde, 0x5d, 0xae, 0x22, 0x23,
                                                 0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c, 0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00, 0x15, 0xad],
              "sha256, abc")
        check(HMACSHA256.authenticate(Array("what do ya want for nothing?".utf8), key: Array("Jefe".utf8))
                == [0x5b, 0xdc, 0xc1, 0x46, 0xbf, 0x60, 0x75, 0x4e, 0x6a, 0x04, 0x24, 0x26, 0x08, 0x95, 0x75, 0xc7,
                    0x5a, 0x00, 0x3f, 0x08, 0x9d, 0x27, 0x39, 0x83, 0x9d, 0xec, 0x58, 0xb9, 0x64, 0xec, 0x38, 0x43],
              "hmac, RFC 4231 case 2")
        // FIPS 180-2's "abc", SHA-512's first and last 8 bytes.
        let abc512 = SHA512.hash(Array("abc".utf8))
        check(abc512.count == 64 && abc512.prefix(8) == [0xdd, 0xaf, 0x35, 0xa1, 0x93, 0x61, 0x7a, 0xba]
                && abc512.suffix(8) == [0x2a, 0x9a, 0xc9, 0x4f, 0xa5, 0x4c, 0xa4, 0x9f], "sha512, abc")
        check(MD5.hash(Array("abc".utf8)) == [0x90, 0x01, 0x50, 0x98, 0x3c, 0xd2, 0x4f, 0xb0,
                                              0xd6, 0x96, 0x3f, 0x7d, 0x28, 0xe1, 0x7f, 0x72], "md5, abc")
        let dk = PBKDF2.sha256(password: Array("passwd".utf8), salt: Array("salt".utf8), iterations: 1, length: 16)
        check(dk == [0x55, 0xac, 0x04, 0x6e, 0x56, 0xe3, 0x08, 0x9f, 0xec, 0x16, 0x91, 0xc2, 0x25, 0x44, 0xb6, 0x05],
              "pbkdf2, RFC 7914")
    }

    static func ciphers() {
        // RFC 8439 §2.3.2's block (its first 8 bytes) and §2.5.2's tag.
        let block = ChaCha20.block(key: (0..<32).map { UInt8($0) }, counter: 1,
                                   nonce: [0, 0, 0, 9, 0, 0, 0, 0x4a, 0, 0, 0, 0])
        check(block.prefix(8) == [0x10, 0xf1, 0xe7, 0xe4, 0xd1, 0x3b, 0x59, 0x15], "chacha20, RFC 8439")
        let polyKey: [UInt8] = [0x85, 0xd6, 0xbe, 0x78, 0x57, 0x55, 0x6d, 0x33, 0x7f, 0x44, 0x52, 0xfe, 0x42, 0xd5, 0x06, 0xa8,
                                0x01, 0x03, 0x80, 0x8a, 0xfb, 0x0d, 0xb2, 0xfd, 0x4a, 0xbf, 0xf6, 0xaf, 0x41, 0x49, 0xf5, 0x1b]
        check(Poly1305.authenticate(Array("Cryptographic Forum Research Group".utf8), key: polyKey)
                == [0xa8, 0x06, 0x1d, 0xc1, 0x30, 0x51, 0x36, 0xc6, 0xc2, 0x2b, 0x8b, 0xaf, 0x0c, 0x01, 0x27, 0xa9],
              "poly1305, RFC 8439")
        // The AEAD round trip, and a changed byte refused.
        let key = (0..<32).map { UInt8($0) }, nonce = [UInt8](repeating: 7, count: 12)
        let message = Array("the one ring".utf8), aad: [UInt8] = [1, 2, 3]
        var sealed = ChaCha20Poly1305.seal(message, key: key, nonce: nonce, aad: aad)
        check(ChaCha20Poly1305.open(sealed, key: key, nonce: nonce, aad: aad) == message, "chacha20-poly1305 opens")
        sealed[0] ^= 1
        check(ChaCha20Poly1305.open(sealed, key: key, nonce: nonce, aad: aad) == nil, "and refuses a changed byte")
    }

    static func curves() {
        // RFC 7748 §6.1: Alice's public key from her private key (its first 8 bytes).
        let alice: [UInt8] = [0x77, 0x07, 0x6d, 0x0a, 0x73, 0x18, 0xa5, 0x7d, 0x3c, 0x16, 0xc1, 0x72, 0x51, 0xb2, 0x66, 0x45,
                              0xdf, 0x4c, 0x2f, 0x87, 0xeb, 0xc0, 0x99, 0x2a, 0xb1, 0x77, 0xfb, 0xa5, 0x1d, 0xb9, 0x2c, 0x2a]
        check(X25519.publicKey(alice).prefix(8) == [0x85, 0x20, 0xf0, 0x09, 0x89, 0x30, 0xa7, 0x54], "x25519, RFC 7748")
        // RFC 8032 §7.1 TEST 2: the public key, the signature, and its check.
        let seed: [UInt8] = [0x4c, 0xcd, 0x08, 0x9b, 0x28, 0xff, 0x96, 0xda, 0x9d, 0xb6, 0xc3, 0x46, 0xec, 0x11, 0x4e, 0x0f,
                             0x5b, 0x8a, 0x31, 0x9f, 0x35, 0xab, 0xa6, 0x24, 0xda, 0x8c, 0xf6, 0xed, 0x4f, 0xb8, 0xa6, 0xfb]
        let edKey = Ed25519.publicKey(seed: seed)
        let edSignature = Ed25519.sign([0x72], seed: seed)
        check(edKey.prefix(8) == [0x3d, 0x40, 0x17, 0xc3, 0xe8, 0x43, 0x89, 0x5a], "ed25519 key, RFC 8032")
        check(edSignature.prefix(8) == [0x92, 0xa0, 0x09, 0xa9, 0xf0, 0xd4, 0xca, 0xb8], "ed25519 signature, RFC 8032")
        check(Ed25519.verify(edSignature, of: [0x72], publicKey: edKey)
                && !Ed25519.verify(edSignature, of: [0x73], publicKey: edKey), "ed25519 verify, RFC 8032")
    }
}
