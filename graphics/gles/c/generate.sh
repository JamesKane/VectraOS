#!/bin/bash
# SPDX-License-Identifier: BSD-3-Clause
#
# Writes the files gles(3) and egl(3) make from the Khronos headers in
# graphics/gles/include: the GL and EGL constants for Swift, and the C entry
# points. Run from the tree's root after a header or the extension list
# changes; the outputs are committed.
#
#   lib/generated/Constants.swift  every GL_ and EGL_ constant of gl2.h and egl.h, and the extensions' below
#   c/libGLESv2.c                  each gl* name, calling libGLES.so's gles_gl* (libGLESv2.so, .so.2)
#   c/libEGL.c                     each egl* name, calling libGLES.so's gles_egl* (libEGL.so, .so.1)
#   c/procs.c                      eglGetProcAddress's table: every name, at libGLES.so's function
set -euo pipefail
cd "$(dirname "$0")/.."
inc=include
# The extensions' constants and functions the library has (gles(3), EXTENSIONS).
ext_constants='GL_WRITE_ONLY_OES GL_BUFFER_ACCESS_OES GL_BUFFER_MAPPED_OES GL_BUFFER_MAP_POINTER_OES
GL_DEPTH_COMPONENT24_OES GL_DEPTH_COMPONENT32_OES GL_DEPTH_STENCIL_OES GL_UNSIGNED_INT_24_8_OES
GL_DEPTH24_STENCIL8_OES GL_RGB8_OES GL_RGBA8_OES GL_BGRA_EXT GL_TEXTURE_MAX_ANISOTROPY_EXT
GL_MAX_TEXTURE_MAX_ANISOTROPY_EXT GL_COLOR_EXT GL_DEPTH_EXT GL_STENCIL_EXT
GL_VERTEX_ARRAY_BINDING_OES'
ext_functions='glMapBufferOES glUnmapBufferOES glGetBufferPointervOES glDiscardFramebufferEXT
glBindVertexArrayOES glDeleteVertexArraysOES glGenVertexArraysOES glIsVertexArrayOES'

prototypes() {  # file prefix-macro entry-macro [names]: "ret|name|params" lines
  local file=$1 api=$2 entry=$3 names=${4:-}
  awk -v api="$api" -v entry="$entry" -v names="$names" '
    BEGIN { n = split(names, want, /[ \n]+/); for (i = 1; i <= n; i++) if (want[i] != "") keep[want[i]] = 1 }
    $1 == api {
      line = $0
      while (line !~ /\);/) { getline more; line = line " " more }
      sub("^" api " +", "", line)
      at = index(line, entry " ")
      ret = substr(line, 1, at - 1); sub(/ +$/, "", ret)
      rest = substr(line, at + length(entry) + 1)
      name = rest; sub(/ *\(.*/, "", name)
      params = rest; sub(/^[^(]*\(/, "", params); sub(/\);.*/, "", params)
      if (names != "" && !(name in keep)) next
      print ret "|" name "|" params
    }' "$file"
}

arguments() {  # "T a, const T *b" -> "a, b"
  awk -v p="$1" 'BEGIN {
    if (p == "void" || p == "") { print ""; exit }
    n = split(p, parts, /,/); out = ""
    for (i = 1; i <= n; i++) { a = parts[i]; sub(/\[.*\]/, "", a); gsub(/[ \t]+$/, "", a); m = split(a, w, /[ *]+/); out = out (i > 1 ? ", " : "") w[m] }
    print out }'
}

forwarders() {  # includes (lines), then prototype lines on stdin
  local includes=$1
  echo "// SPDX-License-Identifier: BSD-3-Clause"
  echo "//"
  echo "// Generated by graphics/gles/c/generate.sh from the Khronos headers. Do not edit."
  echo "// C because these are the C names a program links or dlopens: each calls libGLES.so's own, so that every"
  echo "// name a program opens the library by (libGLESv2.so, libGLESv2.so.2, libEGL.so, libEGL.so.1) reaches one library."
  echo
  echo "$includes"
  while IFS='|' read -r ret name params; do
    args=$(arguments "$params")
    echo
    echo "extern $ret gles_$name($params);"
    if [ "$ret" = "void" ]; then
      echo "$ret $name($params) { gles_$name($args); }"
    else
      echo "$ret $name($params) { return gles_$name($args); }"
    fi
  done
}

gl=$(prototypes $inc/GLES2/gl2.h GL_APICALL GL_APIENTRY; prototypes $inc/GLES2/gl2ext.h GL_APICALL GL_APIENTRY "$(echo $ext_functions)")
egl=$(prototypes $inc/EGL/egl.h EGLAPI EGLAPIENTRY)

forwarders "#include <GLES2/gl2.h>
#define GL_GLEXT_PROTOTYPES 1
#include <GLES2/gl2ext.h>" <<<"$gl" > c/libGLESv2.c
forwarders "#include <EGL/egl.h>" <<<"$egl" > c/libEGL.c

{
  echo "// SPDX-License-Identifier: BSD-3-Clause"
  echo "//"
  echo "// Generated by graphics/gles/c/generate.sh from the Khronos headers. Do not edit."
  echo "// eglGetProcAddress's table (egl(3)): every gl* and egl* name the library has, at its function. C, for the"
  echo "// address of each of the library's C functions, which Swift can't take without spelling each one's type."
  echo
  echo "#include <stddef.h>"
  echo "#include <string.h>"
  echo
  while IFS='|' read -r ret name params; do [ "$name" = eglGetProcAddress ] || echo "extern void gles_$name(void);"; done <<<"$gl
$egl"
  echo "void (*gles_eglGetProcAddress(const char *name))(void);"
  echo
  echo "static const struct { const char *name; void (*function)(void); } procs[] = {"
  while IFS='|' read -r ret name params; do echo "  {\"$name\", (void (*)(void))gles_$name},"; done <<<"$gl
$egl"
  echo "};"
  echo
  echo "// eglGetProcAddress itself: libEGL.so's eglGetProcAddress calls it."
  echo "void (*gles_eglGetProcAddress(const char *name))(void) {"
  echo "  if (name == NULL) return NULL;"
  echo "  for (size_t i = 0; i < sizeof procs / sizeof procs[0]; i++)"
  echo "    if (strcmp(procs[i].name, name) == 0) return procs[i].function;"
  echo "  return NULL;"
  echo "}"
} > c/procs.c

{
  echo "// SPDX-License-Identifier: BSD-3-Clause"
  echo "//"
  echo "// Generated by graphics/gles/c/generate.sh from the Khronos headers. Do not edit."
  echo "// The GL and EGL constants: gl2.h's and egl.h's, and those of the extensions the library has."
  echo
  echo "// swift-format-ignore-file"
  awk '/^#define GL_[A-Z0-9_]+ +(0x[0-9A-Fa-f]+|[0-9]+)$/ { printf "public let %s: GLenum = %s\n", $2, $3 }' $inc/GLES2/gl2.h
  for c in $ext_constants; do
    awk -v c="$c" '$1 == "#define" && $2 == c { printf "public let %s: GLenum = %s\n", $2, $3; exit }' $inc/GLES2/gl2ext.h
  done
  echo "public let GL_SHADER_BINARY_FORMAT_SPIR_V: GLenum = 0x9551"
  awk '/^#define EGL_[A-Z0-9_]+ +(0x[0-9A-Fa-f]+|[0-9]+)$/ { printf "public let %s: EGLint = %s\n", $2, $3 }' $inc/EGL/egl.h
} > lib/generated/Constants.swift
wc -l c/libGLESv2.c c/libEGL.c c/procs.c lib/generated/Constants.swift
