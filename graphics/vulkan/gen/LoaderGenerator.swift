// vkgen --loader (M5f): our Vulkan loader's dispatch, from vk.xml and the
// header's selection. A dispatchable object's first word is its driver's
// dispatch table once the loader has it (the loader-driver interface: the
// driver leaves ICD_LOADER_MAGIC there); the instance table serves
// instances and physical devices, the device table devices, queues and
// command buffers. Each command gets an exported trampoline that finds the
// table and calls the driver's function; the loader's own (Loader.swift)
// are listed in `loaderHandwritten`. Our generator; its output is ours
// (principle 29).

import XMLReader

public let loaderHandwritten: [String] = [
  "vkCreateInstance", "vkDestroyInstance", "vkEnumerateInstanceVersion", "vkEnumerateInstanceExtensionProperties",
  "vkEnumerateInstanceLayerProperties", "vkEnumeratePhysicalDevices", "vkGetInstanceProcAddr", "vkGetDeviceProcAddr",
  "vkCreateDevice", "vkDestroyDevice", "vkGetDeviceQueue", "vkGetDeviceQueue2", "vkAllocateCommandBuffers",
  "vkEnumerateDeviceLayerProperties",
]

public struct LoaderGenerator {
  let h: CHeaderGenerator

  public init(_ header: CHeaderGenerator) { h = header }

  enum Level: Int { case global = 0, instance, physical, device }

  struct Param {
    var name: String
    var type: String
  }

  func swiftScalar(_ t: String) -> String {
    switch t {
    case "uint32_t": return "UInt32"
    case "int32_t", "int": return "Int32"
    case "uint64_t": return "UInt64"
    case "int64_t": return "Int64"
    case "uint16_t": return "UInt16"
    case "int16_t": return "Int16"
    case "uint8_t": return "UInt8"
    case "int8_t": return "Int8"
    case "float": return "Float"
    case "double": return "Double"
    case "size_t": return "Int"
    case "char": return "CChar"
    default: return h.r.types[t]?.attribute("category") == "handle" ? "\(t)?" : t
    }
  }

  /// A parameter's type as Swift imports the C declaration.
  func swiftType(_ e: XMLElement) -> String {
    let type = e.element("type")?.innerText() ?? "void"
    let text = e.innerText(skipping: ["comment"]).trimmingSpace()
    let stars = text.filter { $0 == "*" }.count
    let constFirst = text.hasPrefix("const")
    let base = swiftScalar(type)
    if text.contains("[") { return "UnsafePointer<\(base)>?" }  // an array parameter is a pointer
    switch stars {
    case 0: return base
    case 1:
      if type == "void" { return constFirst ? "UnsafeRawPointer?" : "UnsafeMutableRawPointer?" }
      return constFirst ? "UnsafePointer<\(base)>?" : "UnsafeMutablePointer<\(base)>?"
    default:
      // T** or const T* const*.
      let inner = type == "void" ? (constFirst ? "UnsafeRawPointer?" : "UnsafeMutableRawPointer?")
        : (constFirst ? "UnsafePointer<\(base)>?" : "UnsafeMutablePointer<\(base)>?")
      return text.contains("* const*") ? "UnsafePointer<\(inner)>?" : "UnsafeMutablePointer<\(inner)>?"
    }
  }

  func level(_ name: String, _ params: [XMLElement]) -> Level {
    if ["vkCreateInstance", "vkEnumerateInstanceVersion", "vkEnumerateInstanceExtensionProperties",
        "vkEnumerateInstanceLayerProperties", "vkGetInstanceProcAddr"].contains(name) { return .global }
    switch params.first?.element("type")?.innerText() {
    case "VkInstance": return .instance
    case "VkPhysicalDevice": return .physical
    case "VkDevice", "VkQueue", "VkCommandBuffer": return .device
    default: return .global
    }
  }

  public func generate(source: String) throws(VulkanGenError) -> String {
    var commands: [(name: String, level: Level, params: [XMLElement], returns: String?)] = []
    for c in h.commandNames {
      guard let cmd = h.resolveCommand(c), let proto = cmd.element("proto") else { continue }
      let params = cmd.elements("param").filter(VulkanRegistry.forVulkan)
      let r = proto.element("type")?.innerText() ?? "void"
      let returns: String? = r == "void" ? nil : (r == "PFN_vkVoidFunction" ? "PFN_vkVoidFunction" : swiftScalar(r))
      commands.append((c, level(c, params), params, returns))
    }
    let instanceLevel = commands.filter { $0.level == .instance || $0.level == .physical }
    let deviceLevel = commands.filter { $0.level == .device }
    func name(_ n: String) -> String { "loaderName(\"\(n)\")" }

    var out = """
      // SPDX-License-Identifier: BSD-3-Clause
      //
      // Generated by vkgen --loader from \(source). Do not edit; regenerate (CLAUDE.md, "Generated outputs").
      // The loader's dispatch tables and trampolines for Vulkan up to \(h.selection.maxVersion),
      // with \(h.selection.extensions.joined(separator: ", ")).

      import TDVulkan

      /// A driver's instance-level commands (instances and physical devices).
      @safe public struct VulkanInstanceTable {

      """
    for c in instanceLevel { out += "  public var \(c.name): PFN_\(c.name)?\n" }
    out += "  /// vkGetDeviceProcAddr, to make device tables with.\n"
    out += "  public var vkGetDeviceProcAddr: PFN_vkGetDeviceProcAddr?\n\n"
    out += "  public init(_ gipa: PFN_vkGetInstanceProcAddr, _ instance: VkInstance?) {\n"
    for c in instanceLevel + [(name: "vkGetDeviceProcAddr", level: Level.device, params: [XMLElement](), returns: String?.none)] {
      out += "    unsafe \(c.name) = unsafeBitCast(gipa(instance, \(name(c.name))), to: PFN_\(c.name)?.self)\n"
    }
    out += "  }\n}\n\n"
    out += "/// A driver's device-level commands (devices, queues and command buffers).\n"
    out += "@safe public struct VulkanDeviceTable {\n"
    for c in deviceLevel where c.name != "vkGetDeviceProcAddr" { out += "  public var \(c.name): PFN_\(c.name)?\n" }
    out += "\n  public init(_ gdpa: PFN_vkGetDeviceProcAddr, _ device: VkDevice?) {\n"
    for c in deviceLevel where c.name != "vkGetDeviceProcAddr" {
      out += "    unsafe \(c.name) = unsafeBitCast(gdpa(device, \(name(c.name))), to: PFN_\(c.name)?.self)\n"
    }
    out += "  }\n}\n\n"

    // Trampolines.
    for c in commands where !loaderHandwritten.contains(c.name) && c.level != .global {
      let ps = c.params.map { p -> (String, String) in (p.element("name")?.innerText() ?? "_", swiftType(p)) }
      let list = ps.map { "_ \($0.0): \($0.1)" }.joined(separator: ", ")
      let failure: String
      switch c.returns {
      case nil: failure = "return"
      case "VkResult": failure = "return VK_ERROR_EXTENSION_NOT_PRESENT"
      default: failure = "return 0"
      }
      let first = ps[0].0
      var args = ps.map { $0.0 }
      out += "@c(\(c.name)) public func \(c.name)(\(list))\(c.returns.map { " -> \($0)" } ?? "") {\n"
      switch c.level {
      case .instance:
        out += "  guard let (t, driverInstance) = unsafe loaderFirstDriver(\(first)), let f = unsafe t.pointee.\(c.name) else { \(failure) }\n"
        args[0] = "driverInstance"
      case .physical:
        out += "  guard let f = unsafe loaderInstanceTable(\(first))?.pointee.\(c.name) else { \(failure) }\n"
      default:
        out += "  guard let f = unsafe loaderDeviceTable(\(first))?.pointee.\(c.name) else { \(failure) }\n"
      }
      out += "  return unsafe f(\(args.joined(separator: ", ")))\n}\n\n"
    }

    out += "/// Every command's name and level (0 global, 1 instance, 2 physical device, 3 device), and its entry point.\n"
    out += "let loaderEntries: [(name: StaticString, level: Int, function: PFN_vkVoidFunction)] = unsafe [\n"
    for c in commands.sorted(by: { $0.name < $1.name }) {
      out += "  (\"\(c.name)\", \(c.level.rawValue), unsafeBitCast(\(c.name) as PFN_\(c.name), to: PFN_vkVoidFunction.self)),\n"
    }
    out += "]\n"
    return out
  }
}
