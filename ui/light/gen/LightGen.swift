// Light's tables from the sRGB formula (D110), on the host: tier 0 has no
// libm. Decoding is a byte to linear light in 16 bits, rounded; encoding
// is linear light in 12 bits (the 16 bits' top 12) to the byte nearest,
// by the formula, to the middle of its range. Every decoded byte lands in
// a range of its own that encodes back to it, which `tables` checks.

import Foundation

/// sRGB's transfer: an encoded value (0-1) to linear light (0-1).
public func srgbDecode(_ x: Double) -> Double { x <= 0.04045 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4) }

/// Linear light (0-1) to its sRGB encoding (0-1).
public func srgbEncode(_ x: Double) -> Double { x <= 0.0031308 ? 12.92 * x : 1.055 * pow(x, 1 / 2.4) - 0.055 }

public struct LightTables: Equatable {
  public var decode: [UInt16]
  public var encode: [UInt8]
  /// The text contrast curves, 256 entries for each of `contrastSteps`
  /// settings.
  public var contrast: [UInt8]
}

public enum LightGenError: Error { case inexact(byte: Int) }

/// The settings of `text.contrast` there are curves for: 0 to 1 in
/// twentieths.
public let contrastSteps = 21

/// Setting `step`'s curve at coverage `c` (0-1): 1 - (1 - c)^g, g rising
/// from 1 (the coverage as it is) at setting 0 to 3 at setting 1.
public func contrastCurve(step: Int, _ c: Double) -> Double {
  1 - pow(1 - c, 1 + 2 * Double(step) / Double(contrastSteps - 1))
}

/// The tables, checked to encode every decoded byte back to itself.
public func tables() throws(LightGenError) -> LightTables {
  let decode = (0..<256).map { UInt16((srgbDecode(Double($0) / 255) * 65535).rounded()) }
  let encode = (0..<4096).map { UInt8((srgbEncode((Double($0 * 16) + 7.5) / 65535) * 255).rounded()) }
  for b in 0..<256 where encode[Int(decode[b]) >> 4] != UInt8(b) { throw .inexact(byte: b) }
  let contrast = (0..<contrastSteps).flatMap { step in
    (0..<256).map { UInt8((contrastCurve(step: step, Double($0) / 255) * 255).rounded()) }
  }
  return LightTables(decode: decode, encode: encode, contrast: contrast)
}

/// The tables as Light's source (ui/light/lib/Tables.swift).
public func swiftTables(_ t: LightTables) -> String {
  func rows<T: BinaryInteger>(_ values: [T], _ perRow: Int) -> String {
    stride(from: 0, to: values.count, by: perRow).map { start in
      "    " + values[start..<min(start + perRow, values.count)].map { String($0) }.joined(separator: ", ") + ","
    }.joined(separator: "\n")
  }
  return """
    // SPDX-License-Identifier: BSD-3-Clause
    // Generated by lightgen from the sRGB formula. Do not edit.

    extension Light {
      /// An sRGB byte's linear light, 0-65535.
      static let decodeTable: [UInt16] = [
    \(rows(t.decode, 16))
      ]

      /// Linear light's top 12 bits to the sRGB byte.
      static let encodeTable: [UInt8] = [
    \(rows(t.encode, 24))
      ]
    }

    extension TextContrast {
      /// Each setting's curve, 256 entries a setting, 0 to 1 in twentieths.
      static let curves: [UInt8] = [
    \(rows(t.contrast, 24))
      ]
    }

    """
}
